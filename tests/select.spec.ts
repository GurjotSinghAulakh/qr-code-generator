import { expect, test } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { readFile } from 'node:fs/promises';
import { PNG } from 'pngjs';
import { assertDecodedPayload, decodePixels } from '../src/lib/decode';

test('uses a styled export dropdown and downloads the selected image size', async ({ page }, testInfo) => {
  await page.goto('/');
  const payload = 'https://example.com/component-select';
  await page.getByLabel('Website URL').fill(payload);
  await expect(page.getByText('Scan check passed')).toBeVisible();
  const trigger = page.getByRole('combobox', { name: 'Export size' });
  await expect(trigger).toContainText('1024 × 1024 px');
  await trigger.click();
  const menu = page.getByRole('listbox', { name: 'Export size' });
  await expect(menu).toBeVisible();
  const bounds = await menu.boundingBox();
  const viewport = page.viewportSize()!;
  expect(bounds!.x).toBeGreaterThanOrEqual(0);
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(viewport.width);
  expect(bounds!.y).toBeGreaterThanOrEqual(0);
  expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(viewport.height);
  const accessibility = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze();
  expect(accessibility.violations.map(({ id, nodes }) => ({ id, nodes: nodes.map(({ target, failureSummary }) => ({ target, failureSummary })) }))).toEqual([]);
  await page.screenshot({ path: testInfo.outputPath('export-dropdown.png') });
  await page.getByRole('option', { name: '512 × 512 px', exact: true }).click();
  await expect(menu).toHaveCount(0);
  await expect(trigger).toBeFocused();
  await expect(page.locator('#root')).not.toHaveAttribute('inert');
  await expect(trigger).toContainText('512 × 512 px');
  await expect(page.getByRole('button', { name: 'Download PNG' })).toBeEnabled();
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download PNG' }).click();
  const path = testInfo.outputPath('selected-size.png');
  await (await download).saveAs(path);
  const png = PNG.sync.read(await readFile(path));
  expect(png.width).toBe(512);
  expect(png.height).toBe(512);
  expect(() => assertDecodedPayload(decodePixels(new Uint8ClampedArray(png.data), png.width, png.height), payload)).not.toThrow();
  await trigger.click();
  await expect(page.getByRole('option', { name: '512 × 512 px', exact: true })).toBeFocused();
  await page.mouse.move(5, 5);
  await page.mouse.click(5, 5);
  await expect(menu).toHaveCount(0);
  await expect(trigger).toContainText('512 × 512 px');
});

test('supports keyboard navigation, Escape, and typeahead for network security', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Wi-Fi', exact: true }).click();
  await page.getByLabel('Network name (SSID)').fill('Guest network');
  const security = page.getByRole('combobox', { name: 'Network security' });
  await security.focus();
  await security.press('ArrowDown');
  await expect(page.getByRole('listbox')).toBeVisible();
  await page.keyboard.press('End');
  await page.keyboard.press('Escape');
  await expect(security).toBeFocused();
  await expect(security).toContainText('WPA / WPA2 Personal');
  await expect(page.getByLabel('Network password')).toBeVisible();
  await security.press('Enter');
  await page.keyboard.type('Open');
  await expect(page.getByRole('option', { name: 'Open network (no password)', exact: true })).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(security).toBeFocused();
  await expect(security).toContainText('Open network (no password)');
  await expect(page.getByLabel('Network password')).toHaveCount(0);
  await expect(page.getByText('Scan check passed')).toBeVisible();
});

test('applies correction changes and reflects a controlled design reset', async ({ page }) => {
  await page.goto('/');
  await page.getByLabel('Website URL').fill('https://example.com');
  await page.getByText('Advanced settings', { exact: true }).click();
  const correction = page.getByRole('combobox', { name: 'Error correction' });
  await correction.click();
  await page.getByRole('option', { name: 'Q · High', exact: true }).click();
  await expect(correction).toContainText('Q · High');
  await expect(page.getByText('Scan check passed')).toBeVisible();
  await correction.press('Enter');
  await expect(page.getByRole('option', { name: 'Q · High', exact: true })).toBeFocused();
  await page.keyboard.press('Home');
  await expect(page.getByRole('option', { name: 'L · Low', exact: true })).toBeFocused();
  await page.keyboard.press('ArrowDown');
  await expect(page.getByRole('option', { name: 'M · Standard', exact: true })).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(correction).toContainText('M · Standard');
  await correction.click();
  await page.getByRole('option', { name: 'H · Highest', exact: true }).click();
  await page.getByRole('button', { name: 'Reset design' }).click();
  await expect(correction).toContainText('M · Standard');
  await expect(page.getByText('Scan check passed')).toBeVisible();
});
